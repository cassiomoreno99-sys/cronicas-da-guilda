import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {applyAction,missions,newCampaign} from "../lib/game.ts";
const c=readFileSync("app/arena-3d.tsx","utf8");
const main=readFileSync("app/game-client.tsx","utf8");
const scene=readFileSync("app/arena-3d.css","utf8");
assert.match(c,/new THREE\.WebGLRenderer/,"3D precisa ser WebGL de verdade.");
assert.match(c,/new GLTFLoader/,"Modelos tridimensionais não são carregados.");
assert.match(c,/cloneSkinned\(glb\.scene\)/,"Rig 3D animado não foi integrado.");
assert.match(c,/THREE\.AnimationMixer/,"Faltam animações reais dos personagens.");
assert.match(c,/new OrbitControls/,"Sem controle real da câmera 3D.");
assert.match(c,/actionFromRealLog\(lastLog,log\)/,"Golpes não seguem o resultado da missão.");
assert.match(c,/expedition\.battle/,"A Arena 3D está desconectada das expedições.");
assert.doesNotMatch(c,/SCRIPT:\s*Move|simulateDemo\(/,"Roteiro de simulação fake não é permitido.");
assert.match(main,/<Arena3D key=\{expedition\.id\}/,"3D fora do painel da batalha.");
assert.match(main,/setShow3d\(true\)/,"Botão abrir arena 3D indisponível.");
assert.doesNotMatch(main,/import ArenaDemo from/,"Demo antiga não deve ser importada.");
assert.match(scene,/\.arena-3d-stage canvas/);
const seed=newCampaign(20261013);seed.event=null;
const mission=missions(seed)[0];
const started=applyAction(seed,{type:"mission",missionId:mission.id,team:seed.team,tactic:"balanced",startedAt:1_700_000_000_000,expeditionSlot:1});
const exp=started.expeditions[0];
assert.equal(exp.battle.status,"active");
const actual=applyAction(started,{type:"expedition-tick",now:exp.nextRoundAt});
const fight=actual.expeditions[0].battle;
assert.equal(fight.rounds,1);
assert.ok(fight.log.length>0);
const first=fight.log.find(x=>x.actorId&&x.targetId);
assert.ok(first,"Motor precisa fornecer IDs reais de atacante/alvo para a arena 3D.");
assert.ok(fight.combat?.fighters.some(x=>x.id===first.actorId));
assert.ok(fight.combat?.fighters.some(x=>x.id===first.targetId));
const before={gold:actual.gold,expedition:actual.expeditions[0].id,hp:fight.combat?.fighters.map(x=>x.hp)};
assert.equal(before.gold,actual.gold,"Renderizar 3D não pode cobrar ouro.");
console.log("ARENA 3D/MOTOR OK: combate verdadeiro fornece personagens, HP e ações; sem simulação fixa.");
