import assert from "node:assert/strict";
import {SUPREME_BOOK_IDS,supremeSpectacle,bossSpectacle,spectacleTargets,bossPressure} from "../lib/combat-spectacle-plan.ts";
const h={id:"hero-1",side:"hero" as const},enemy={id:"enemy-0",side:"enemy" as const};
const e={actorId:"hero-1",kind:"ability" as const,text:"Aric usa Poder Supremo."};
assert.equal(SUPREME_BOOK_IDS.length,21,"Todos 14 CG e 7 imperiais");
assert.equal(new Set(SUPREME_BOOK_IDS).size,21);
for(const book of SUPREME_BOOK_IDS){
 const plan=supremeSpectacle({effect:"supreme",id:"supreme-"+book},h,e);
 assert.equal(plan?.kind,"supreme");assert.ok(plan!.points>=8);
 assert.equal(plan?.book,book);
 assert.equal(supremeSpectacle({effect:"supreme",id:"supreme-"+book},enemy,e),undefined);
 assert.equal(supremeSpectacle({effect:"fireball",id:"supreme-"+book},h,e),undefined);
}
assert.equal(supremeSpectacle({effect:"supreme",id:"supreme-FAKE"},h,e),undefined);
assert.equal(supremeSpectacle({effect:"supreme",id:"story-abc"},h,e),undefined);
assert.equal(supremeSpectacle({effect:"supreme",id:"supreme-CG-309"},h,e,true)?.duration,520);
const boss={kind:"boss" as const,boss:0};
const ev=(text:string,kind:"ability"|"heal"|"fall")=>({actorId:"enemy-0",targetId:"hero-1",text,kind});
assert.equal(bossSpectacle(boss,enemy,ev("O Vigia libera uma onda sombria em Lyra: 25 de dano.","ability"))?.kind,"boss-wave");
assert.equal(bossSpectacle({kind:"boss",boss:2},enemy,ev("O guardião libera uma onda contra Lyra: 25 de dano.","ability"))?.kind,"boss-wave");
assert.equal(bossSpectacle({kind:"boss",boss:1},enemy,ev("A Matriarca drena a névoa e recupera 80 PV.","heal"))?.kind,"boss-drain");
assert.equal(bossSpectacle({kind:"boss",boss:4},enemy,ev("O guardião invade a retaguarda e golpeia Lyra: 55 de dano.","ability"))?.kind,"boss-rearguard");
assert.equal(bossSpectacle(boss,enemy,ev("O Vigia libera uma onda sombria em Lyra: 25 de dano.","fall"))?.kind,"boss-wave");
assert.equal(bossSpectacle(boss,enemy,ev("O Vigia libera uma onda sombria em Lyra: 25 de dano.","heal")),undefined);
assert.equal(bossSpectacle({kind:"hunt"},enemy,ev("O Vigia libera uma onda sombria em Lyra: 25 de dano.","ability")),undefined);
assert.equal(bossSpectacle(boss,{id:"enemy-1",side:"enemy"},ev("O Vigia libera uma onda sombria em Lyra: 25 de dano.","ability")),undefined);
assert.equal(bossSpectacle(boss,enemy,ev("Inimigo ataca normalmente: 11 de dano.","ability")),undefined);
assert.equal(bossSpectacle(boss,enemy,ev("O guardião ergue barreiras.","ability")),undefined);
assert.deepEqual(spectacleTargets([{x:15,y:20},{x:75,y:40},{x:101,y:-2},{x:NaN,y:50}]),[{x:15,y:20},{x:75,y:40},{x:100,y:0}]);
assert.equal(bossPressure(100,100),"stable");assert.equal(bossPressure(55,100),"strained");assert.equal(bossPressure(25,100),"critical");
