import assert from "node:assert/strict";
import { newCampaign, normalizeCampaign, applyAction, seasonDay, SEASON_DAYS, missions, type Campaign } from "../lib/game.ts";
import { storageCapacity, storageUsed, chestCapacity } from "../lib/storage.ts";
import { CATALOG_ITEMS, equippedPosition } from "../lib/catalog-test.ts";
import { HQ_BUILDINGS } from "../lib/v130-content.ts";
const noEvent=(s:Campaign)=>({...s,event:null});
const chooseEvent=(s:Campaign)=>s.event?applyAction(s,{type:"event",eventId:s.event.id,choiceId:(s.event.choices.find(c=>!c.cost)||s.event.choices[0]).id}):s;
let s=newCampaign(123456);s.event=null;
assert.equal(SEASON_DAYS,60);
assert.equal(s.calendarVersion,2);
assert.equal(seasonDay(s),1);assert.equal(s.season,1);
assert.equal(chestCapacity(s),30);assert.equal(storageCapacity(10),300);
for(let n=1;n<=10;n++)assert.equal(storageCapacity(n),30+(n-1)*30);
assert.ok(Object.values(HQ_BUILDINGS).every(x=>x.max===10),"Todas as estruturas vão até 10");
let hero=s.heroes[0];
const item=CATALOG_ITEMS.find(x=>x.nivel<=hero.level&&x.classes.includes("Guerreiro")&&x.slot&&!["Materiais","Outros","Consumíveis"].includes(x.categoria)&&equippedPosition(x.id));
assert.ok(item,"Falta equipamento inicial compatível para testar");
s.chest=[{id:"item-1",key:item!.id}];s.itemSequence=1;
assert.equal(storageUsed(s.chest),1);
s=applyAction(s,{type:"equip",itemId:"item-1",heroId:hero.id});
assert.equal(storageUsed(s.chest),0,"Item equipado ainda conta no baú");
assert.equal(s.chest[0].equippedTo,hero.id);
assert.ok(s.chest[0].equippedSlot,"O item deve ocupar um dos doze espaços");
s=applyAction(s,{type:"unequip",itemId:"item-1"});
assert.equal(storageUsed(s.chest),1);
assert.equal(s.chest[0].equippedTo,undefined);
s.gold=1000000;
for(let i=2;i<=30;i++)s.chest.push({id:"item-"+i,key:item!.id});
assert.equal(storageUsed(s.chest),30);
s=applyAction(s,{type:"equip",itemId:"item-1",heroId:hero.id});
assert.equal(storageUsed(s.chest),29,"Equipar deve liberar uma vaga");
s.chest.push({id:"item-31",key:item!.id});assert.equal(storageUsed(s.chest),30);
assert.throws(()=>applyAction(s,{type:"unequip",itemId:"item-1"}),/espaço no baú/i,"Não deve devolver item ao baú cheio");
s=applyAction(s,{type:"upgrade-hq",building:"warehouse"});
assert.equal(chestCapacity(s),60);
s=applyAction(s,{type:"unequip",itemId:"item-1"});
assert.equal(storageUsed(s.chest),31,"Item desequipado volta ao baú");
for(let n=2;n<=9;n++)s=applyAction(s,{type:"upgrade-hq",building:"warehouse"});
assert.equal(s.hq.warehouse,10);
assert.equal(chestCapacity(s),300);
assert.throws(()=>applyAction(s,{type:"upgrade-hq",building:"warehouse"}),/máximo/i);
let start=s.day;
s=applyAction(s,{type:"rest"});
assert.equal(s.day,start,"Descanso passou o dia");
assert.throws(()=>applyAction(s,{type:"rest"}),/descansou hoje/i);
s=applyAction(s,{type:"train-hero",heroId:hero.id});
assert.equal(s.day,start,"Treino individual passou o dia");
s=applyAction(s,{type:"next-day"});
assert.equal(s.day,start+1);
assert.equal(seasonDay(s),2);
s.event=null;
for(let i=2;i<=60;i++){s=chooseEvent(s);s=applyAction(s,{type:"next-day"});}
assert.equal(s.season,2);
assert.equal(seasonDay(s),1);
assert.equal(s.day,61);
const old=newCampaign(5);
delete old.calendarVersion;
old.season=3;old.day=64;old.event=null;
old.heroes[0].level=8;old.gold=32100;old.chest=[{id:"item-100",key:item!.id,equippedTo:old.heroes[0].id,equippedSlot:"weapon"}];
const saved=normalizeCampaign(old);
assert.equal(saved.season,3);
assert.equal(seasonDay(saved),((64-1)%28)+1,"Migração deve preservar dia da temporada antiga");
assert.equal(saved.heroes[0].level,8);assert.equal(saved.gold,32100);
assert.equal(saved.chest.length,1);assert.equal(storageUsed(saved.chest),0);
const startBattle=newCampaign(12345);startBattle.event=null;
const mission=missions(startBattle)[0];
const onMission=applyAction(startBattle,{type:"mission",missionId:mission.id,team:startBattle.team,tactic:"balanced",expeditionSlot:1,startedAt:1000000});
assert.equal(onMission.day,1);
assert.throws(()=>applyAction(onMission,{type:"next-day"}),/expedições ativas/i);
const completed=applyAction(onMission,{type:"battle-auto",expeditionId:onMission.expeditions[0].id});
assert.equal(completed.day,1,"Finalizar batalha não pode avançar o dia");
const another=applyAction(completed,{type:"next-day"});assert.equal(another.day,2,"Dia só avança com o botão");
