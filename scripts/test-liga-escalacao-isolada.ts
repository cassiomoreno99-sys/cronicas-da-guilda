import assert from "node:assert/strict";
import {newCampaign,applyAction,missions,leagueLineup,normalizeCampaign} from "../lib/game.ts";
let matches=0,forfeits=0;
for(let seed=0;seed<80;seed++){
 let s=newCampaign(948100+seed*19);s.event=null;s.gold=100000;
 const official=s.heroes.slice(0,4).map(h=>h.id);
 const expeditionTeam=s.heroes.slice(2,6).map(h=>h.id);
 s=applyAction(s,{type:"league-lineup",team:official,tactic:"defensive"});
 assert.deepEqual(s.leagueTeam,official);
 assert.equal(s.leagueTactic,"defensive");
 const before=JSON.stringify({team:s.leagueTeam,tactic:s.leagueTactic,formation:s.leagueFormation});
 s=applyAction(s,{type:"mission",missionId:missions(s)[0].id,team:expeditionTeam,tactic:"aggressive"});
 assert.deepEqual(s.leagueTeam,official,"A missão substituiu a equipe oficial da Liga");
 assert.equal(s.leagueTactic,"defensive","A missão substituiu a tática da Liga");
 assert.deepEqual(s.expeditions.at(-1)!.team,expeditionTeam,"Missão perdeu a escalação própria");
 assert.equal(s.expeditions.at(-1)!.tactic,"aggressive");
 const id=s.expeditions.at(-1)!.id;
 s=applyAction(s,{type:"battle-auto",expeditionId:id});
 assert.equal(s.leagueTactic,"defensive");
 assert.ok(s.leagueTeam?.every(id=>official.includes(id)));
 const restored=normalizeCampaign(JSON.parse(JSON.stringify(s)));
 assert.equal(JSON.stringify({team:restored.leagueTeam,tactic:restored.leagueTactic,formation:restored.leagueFormation}),before,"Salvamento perdeu escalação oficial");
 const lineup=leagueLineup(restored);
 assert.ok(lineup.ids.every(id=>official.includes(id)),"Heróis da missão entraram na Liga sem autorização");
 restored.event=null;
 s=applyAction(restored,{type:"next-day"});
 assert.equal(s.leagueHistory[0].tactic,"defensive","Partida da Liga usou tática da expedição");
 matches++;
 if(s.leagueHistory[0].forfeit)forfeits++;
}
const old=newCampaign(7733);old.event=null;
delete old.leagueTeam;delete old.leagueFormation;delete old.leagueTactic;
const migrated=normalizeCampaign(old);
assert.deepEqual(migrated.leagueTeam,old.team,"Save antigo não migrou a escalação");
assert.equal(migrated.leagueTactic,old.tactic,"Save antigo não migrou a tática");
console.log("LIGA ISOLADA: "+matches+" partidas com escalação oficial preservada entre missão, combate, save e novo dia. W.O. válidos: "+forfeits+".");
