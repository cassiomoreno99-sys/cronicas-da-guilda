import assert from "node:assert/strict";
import {newCampaign,applyAction,normalizeCampaign,standings} from "../lib/game.ts";
import {chestCapacity,storageUsed} from "../lib/storage.ts";
let deliveries=0,queued=0;
for(let seed=0;seed<100;seed++){
 let s=newCampaign(84000+seed*41);s.event=null;s.gold=100000;s.day=60;s.season=1;s.points=100000;
 s.heroes[0].level=50;s.heroes[0].attack=9000;s.heroes[0].defense=9000;s.heroes[0].magic=9000;
 const cap=chestCapacity(s);
 s.chest=Array.from({length:cap},(_,i)=>({id:"item-"+(i+1),key:"CG-001"}));
 s.itemSequence=cap;
 assert.equal(storageUsed(s.chest),cap);
 s=applyAction(s,{type:"next-day"});
 assert.equal(s.season,2);
 assert.ok(s.seasonAwards?.[0].guildPlace!<=3,"Não ficou entre as três melhores");
 assert.equal(storageUsed(s.chest),cap,"Prêmio desrespeitou limite de baú");
 assert.ok((s.pendingRewards?.length||0)>=4,"O kit não foi enfileirado corretamente");
 assert.ok(s.seasonForgePlans?.[0].materials);
 const previous=s.pendingRewards!.length;
 const json=JSON.stringify(s);
 s=normalizeCampaign(JSON.parse(json));
 assert.equal(s.pendingRewards!.length,previous,"Backup perdeu os prêmios em espera");
 assert.throws(()=>applyAction(s,{type:"claim-pending-rewards"}),/Baú cheio/);
 const freed=Math.min(previous,5);
 s.chest.splice(0,freed);
 assert.equal(storageUsed(s.chest),cap-freed);
 s=applyAction(s,{type:"claim-pending-rewards"});
 assert.equal(storageUsed(s.chest),cap);
 assert.equal(s.pendingRewards!.length,previous-freed);
 assert.equal(new Set([...s.chest,...s.pendingRewards!].map(i=>i.id)).size,s.chest.length+s.pendingRewards!.length,"ID de prêmio duplicado");
 queued+=previous;deliveries+=freed;
}
console.log("PREMIAÇÃO E CAPACIDADE: 100 temporadas premiadas com baú cheio, "+queued+" recompensas enfileiradas e "+deliveries+" resgatadas sem perdas/duplicações.");
